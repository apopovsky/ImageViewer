pub fn load_saved_language() -> Language {
    let hkcu = RegKey::predef(HKEY_CURRENT_USER);
    if let Ok(key) = hkcu.open_subkey(REG_SUBKEY) {
        if let Ok(code) = key.get_value::<String, _>(REG_VALUE_LANG) {
            if let Some(lang) = Language::from_code(&code) {
                return lang;
            }
        }
    }
    Language::English
}

pub fn save_language(lang: Language) {
    let hkcu = RegKey::predef(HKEY_CURRENT_USER);
    if let Ok((key, _)) = hkcu.create_subkey(REG_SUBKEY) {
        let _ = key.set_value(REG_VALUE_LANG, &lang.code());
    }
}

