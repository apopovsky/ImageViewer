#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn default_language_is_english() {
        assert_eq!(Language::default(), Language::English);
        assert_eq!(Language::default().code(), "en");
    }

    #[test]
    fn from_code_roundtrips_all_languages() {
        for lang in Language::ALL {
            assert_eq!(Language::from_code(lang.code()), Some(lang));
            assert_eq!(Language::from_code(&lang.code().to_uppercase()), Some(lang));
        }
        assert_eq!(Language::from_code("en-US"), Some(Language::English));
        assert_eq!(Language::from_code("es-AR"), Some(Language::Spanish));
        assert_eq!(Language::from_code("pt_BR"), Some(Language::Portuguese));
        assert_eq!(Language::from_code("unknown"), None);
    }

    #[test]
    fn all_languages_have_non_empty_core_strings() {
        for lang in Language::ALL {
            let t = lang.tr();
            assert!(!t.btn_open.is_empty());
            assert!(!t.welcome_title.is_empty());
            assert!(!t.assoc_title.is_empty());
            assert!(!t.info_heading.is_empty());
            assert!(!lang.display_name().is_empty());
        }
    }
}
